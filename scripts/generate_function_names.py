"""
Regenerate sqlalchemy_dialect/functions.py from an opteryx-core checkout.

    python scripts/generate_function_names.py ../opteryx-core

The names come from the engine's exported catalogs in `reference/`:
scalar functions and their aliases (function_signatures.json), and the
callable spellings of aggregates (aggregates.json) and window functions
(windows.json), read from each entry's `sql_forms`. A few functions are
handled by the planner itself and are not in any catalog; they are listed in
PLANNER_FUNCTIONS below.

Run it before each release so clients (Apache Superset's SQL Lab
autocomplete, for one) offer what the service accepts.
"""

import json
import re
import sys
from pathlib import Path

# Rewritten or bound by the planner rather than registered in a catalog.
PLANNER_FUNCTIONS = {"DATE_TRUNC", "DATETRUNC", "GROUPING"}

_CALL = re.compile(r"^([A-Z_][A-Z0-9_]*)\s*\(")

_OUTPUT = Path(__file__).resolve().parent.parent / "sqlalchemy_dialect" / "functions.py"

_HEADER = '''"""
Names of the functions the Opteryx engine accepts: scalar functions and their
aliases, aggregates and window functions.

Generated by scripts/generate_function_names.py from opteryx-core's
reference catalogs; do not edit by hand. Clients use it for autocomplete
without running a query (every query counts against the account's quota).
"""

FUNCTION_NAMES: tuple = (
'''


def _called_names(entries: dict) -> set:
    names = set()
    for entry in entries.values():
        for form in entry.get("sql_forms") or []:
            match = _CALL.match(form)
            if match:
                names.add(match.group(1))
    return names


def collect(core: Path) -> list:
    reference = core / "reference"
    scalars = json.loads((reference / "function_signatures.json").read_text())
    aggregates = json.loads((reference / "aggregates.json").read_text())
    windows = json.loads((reference / "windows.json").read_text())

    names = set(PLANNER_FUNCTIONS)
    for name, entry in scalars.items():
        if entry.get("lifecycle", {}).get("status", "active") != "active":
            continue
        names.add(name)
        names.update(entry.get("aliases") or [])
    names |= _called_names({k: v for k, v in aggregates.items() if v.get("status") == "active"})
    names |= _called_names(windows["functions"])
    return sorted(name for name in names if not name.startswith("_"))


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    names = collect(Path(sys.argv[1]))
    body = "".join(f'    "{name}",\n' for name in names)
    _OUTPUT.write_text(_HEADER + body + ")\n")
    print(f"wrote {len(names)} names to {_OUTPUT}")


if __name__ == "__main__":
    main()
